class RandomizeRobotMaterialExceptPaddle(randomize_rigid_body_material):
    """Keep the authored paddle material while sampling the other robot shapes."""

    def __call__(
        self,
        env: ManagerBasedEnv,
        env_ids: torch.Tensor | None,
        static_friction_range: tuple[float, float],
        dynamic_friction_range: tuple[float, float],
        restitution_range: tuple[float, float],
        num_buckets: int,
        asset_cfg: SceneEntityCfg,
        make_consistent: bool = False,
    ):
        view = self.asset.root_physx_view
        env_ids = torch.arange(env.scene.num_envs, device="cpu") if env_ids is None else env_ids.cpu()

        hand_path = next(path for path in view.link_paths[0] if path.endswith("/right_hand_link"))
        stage = omni.usd.get_context().get_stage()
        collider = stage.GetPrimAtPath(f"{hand_path}/collisions/mesh_1/cylinder")
        material, _ = UsdShade.MaterialBindingAPI(collider).ComputeBoundMaterial("physics")
        rubber = UsdPhysics.MaterialAPI(material.GetPrim())
        materials = view.get_material_properties()
        authored = materials.new_tensor((
            rubber.GetStaticFrictionAttr().Get(),
            rubber.GetDynamicFrictionAttr().Get(),
            rubber.GetRestitutionAttr().Get(),
        ))
        # Match the authored material rather than relying on PhysX shape order.
        paddle_mask = torch.isclose(materials[env_ids], authored).all(dim=-1)
        if not torch.all(paddle_mask.sum(dim=-1) == 1):
            raise RuntimeError("Expected exactly one collider with the authored paddle material per environment")

        bucket_ids = torch.randint(0, num_buckets, (len(env_ids), view.max_shapes), device="cpu")
        samples = self.material_buckets[bucket_ids]
        materials[env_ids] = torch.where(paddle_mask.unsqueeze(-1), authored, samples)
        view.set_material_properties(materials, env_ids)


def reset_joints_by_scale_debug(
    env: ManagerBasedEnv,
    env_ids: torch.Tensor,
    position_range: tuple[float, float],
    velocity_range: tuple[float, float],
    asset_cfg: SceneEntityCfg = SceneEntityCfg("robot"),
):
    """Reset the robot joints by scaling the default position and velocity by the given ranges.

    This function samples random values from the given ranges and scales the default joint positions and velocities
    by these values. The scaled values are then set into the physics simulation.
    """
    # extract the used quantities (to enable type-hinting)
    asset: Articulation = env.scene[asset_cfg.name]
    
    # cast env_ids to allow broadcasting
    if asset_cfg.joint_ids != slice(None):
        iter_env_ids = env_ids[:, None]
    else:
        iter_env_ids = env_ids

    # get default joint state
    joint_pos = asset.data.default_joint_pos[iter_env_ids, asset_cfg.joint_ids].clone()
    joint_vel = asset.data.default_joint_vel[iter_env_ids, asset_cfg.joint_ids].clone()

    # scale these values randomly
    joint_pos *= math_utils.sample_uniform(*position_range, joint_pos.shape, joint_pos.device)
    joint_vel *= math_utils.sample_uniform(*velocity_range, joint_vel.shape, joint_vel.device)

    # clamp joint pos to limits
    joint_pos_limits = asset.data.soft_joint_pos_limits[iter_env_ids, asset_cfg.joint_ids]
    joint_pos = joint_pos.clamp_(joint_pos_limits[..., 0], joint_pos_limits[..., 1])
    # clamp joint vel to limits
    joint_vel_limits = asset.data.soft_joint_vel_limits[iter_env_ids, asset_cfg.joint_ids]
    joint_vel = joint_vel.clamp_(-joint_vel_limits, joint_vel_limits)

    # set into the physics simulation
    asset.write_joint_state_to_sim(joint_pos, joint_vel, joint_ids=asset_cfg.joint_ids, env_ids=env_ids)

